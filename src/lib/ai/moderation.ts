/**
 * 生成された会話ターンに固有名詞らしき文字列(実名・会社名・部署名など)が
 * 混入していないかを検査する(docs/05-ai-pipeline.md §4 生成後の検証)。
 *
 * `server-only` を import しない純粋モジュールとして切り出す
 * (`lib/ai/conversation.ts` から使われるほか、`tests/` から直接検証できるように)。
 */

// finding #10: 旧パターンは `[一-龠々ぁ-ん]{1,6}部` / `課` / 裸の `様` を
// マッチさせており、「全部」「一部」「同様」「様子」のようなごく普通の
// 日本語まで固有名詞として検出していた(1文字の漢字+部/課でもマッチしてしまう
// うえ、`様` は前後の文脈を一切見ていなかった)。誤検出はリトライの浪費・
// 正常なターンの黙って削除・不要なフォールバック行きにつながっていた。
//
// 実在しそうな固有名詞だけに絞る:
// - 会社の法人格(株式会社/有限会社/合同会社)はそのまま強いシグナルなので維持。
// - 部署名らしき文字列は「2〜6文字の漢字の連続 + 部/課」に限定する。
//   全部/一部は漢字1文字+部/課なのでマッチしない。品質保証部(漢字4文字+部)は
//   マッチする。
// - 支店は語として固定。
// - 人名敬称(さん/様)は、直前にカタカナの連続(2文字以上)が無ければ
//   マッチさせない。日常語の「同様」「様子」はどちらも敬称の直前がカタカナで
//   はない(漢字/文頭)ためマッチしない。
export const FORBIDDEN_PATTERN =
  /(株式会社|有限会社|合同会社|[一-龠]{2,6}(?:部|課)|支店|[ァ-ヶー]{2,}(?:さん|様))/u;

/** 1件のテキストに禁止語(固有名詞らしき文字列)が含まれるか */
export function containsForbiddenContent(text: string): boolean {
  return FORBIDDEN_PATTERN.test(text);
}
